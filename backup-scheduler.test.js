const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createBackupScheduler, BACKUP_INTERVAL_MS } = require('./backup-scheduler');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'payroll-backup-test-'));
let time = new Date('2026-10-10T06:00:00Z');
let calls = 0;
let fail = false;
const options = { directory, now: () => time, getProvider: () => 'test', getPayload: async () => {
  calls++;
  if (fail) throw Error('Database unavailable');
  return { employees: [{ employeeId: 'E001' }], entries: [], companies: [], reports: [] };
} };
(async () => {
  const scheduler = createBackupScheduler(options);
  const results = await Promise.all([scheduler.check(), scheduler.check()]);
  assert.equal(calls, 1, 'Concurrent checks create only one backup');
  assert.equal(results[0].createdThisCheck, true);
  assert.equal(scheduler.list().length, 1);
  const envelope = JSON.parse(fs.readFileSync(scheduler.list()[0].fullPath, 'utf8'));
  assert.equal(envelope.payload.employees[0].employeeId, 'E001');
  assert.equal(envelope.kind, 'routes-payroll-weekly-emergency-backup');
  assert.equal(fs.statSync(scheduler.list()[0].fullPath).mode & 0o777, 0o600);
  time = new Date(time.getTime() + BACKUP_INTERVAL_MS - 1);
  assert.equal((await scheduler.check()).createdThisCheck, false);
  assert.equal(calls, 1);
  time = new Date(time.getTime() + 1);
  assert.equal((await scheduler.check()).createdThisCheck, true);
  assert.equal(scheduler.list().length, 2);
  time = new Date(time.getTime() + BACKUP_INTERVAL_MS * 2);
  fail = true;
  await assert.rejects(scheduler.check(), /Database unavailable/);
  assert.equal(scheduler.list().length, 2, 'Failed backup preserves previous backups');
  assert.equal(scheduler.status().overdue, true);
  fail = false;
  const restarted = createBackupScheduler(options);
  assert.equal((await restarted.check()).createdThisCheck, true, 'Restart catches up overdue backup');
  assert.equal(restarted.list().length, 3);
  assert.equal(fs.readdirSync(directory).some((name) => name.endsWith('.tmp')), false);
  console.log('Backup scheduler tests passed: initial backup, seven-day interval, concurrency, private files, failure preservation, and restart catch-up.');
})().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => fs.rmSync(directory, { recursive: true, force: true }));
